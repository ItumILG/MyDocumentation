def area(x, y):
    '''
    Принимает длину и ширину прямоугольника, 
    возвращает его площадь.

    Параметры:
        x (int, float): длина прямоугольника
        y (int, float): ширина прямоугольника

    Возвращаемое значение:
        int, float: площадь прямоугольника

    Пример вызова:
        area(5, 10) -> 50
    '''
    return x * y


def perimeter(x, y):
    '''
    Принимает длину и ширину прямоугольника, 
    возвращает его периметр.

    Параметры:
        x (int, float): длина прямоугольника
        x (int, float): ширина прямоугольника

    Возвращаемое значение:
        int, float: периметр прямоугольника

    Пример вызова:
        perimeter(5, 10) -> 30
    '''
    return 2 * (x + y)