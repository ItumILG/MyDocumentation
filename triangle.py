def area(a, h):
    '''
    Принимает сторону треугольника и высоту, опущенную на нее, 
    возвращает площадь треугольника.

    Параметры:
        a (int, float): сторона треугольника
        h (int, float): высота треугольника

    Возвращаемое значение:
        float: площадь треугольника

    Пример вызова:
        area(10, 5) -> 25.0
    '''
    return 0.5 * a * h


def perimeter(a, b, c):
    '''
    Принимает длины трех сторон треугольника, 
    возвращает его периметр.

    Параметры:
        a (int, float): первая сторона
        b (int, float): вторая сторона
        c (int, float): третья сторона

    Возвращаемое значение:
        int, float: периметр треугольника

    Пример вызова:
        perimeter(3, 4, 5) -> 12
    '''
    return a + b + c